export function metricInfo(key,rows){
 const code=identity(rows[0]||{name:key.split(' | ')[0],code:''});
 const d=definitions[code]||[rows[0]?.name||code,'其他辅助项目',99,'报告中的辅助项目，具体意义需结合样本、方法与临床情况。'];
 const latest=[...rows].sort((a,b)=>a.date.localeCompare(b.date)).at(-1);
 const abnormal=!!latest?.flag;
 return {code,name:d[0],category:d[1],rank:d[2],description:d[3],abnormal,
  priority:d[1]==='肿瘤随访'?'高 · 肿瘤随访':abnormal?'重点 · 报告异常':'常规备查',
  label:`${d[0]}${code!==d[0]?`（${code}）`:''} · ${key.split(' | ')[1]||''}`};
}
